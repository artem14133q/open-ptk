// Whether a CP1251 text is the UTF-8 one, spaces at either end aside.
static int same_text(const char *cp1251, const char *utf8) {
    char a[1024];
    cp1251_to_utf8(cp1251, a, sizeof(a));
    const char *s = a, *t = utf8;
    while (*s == ' ') s++;
    while (*t == ' ') t++;
    size_t ns = strlen(s), nt = strlen(t);
    while (ns && s[ns - 1] == ' ') ns--;
    while (nt && t[nt - 1] == ' ') nt--;
    return ns == nt && memcmp(s, t, ns) == 0;
}

void phrasefix_apply(Game *g) {
    if (g->game != 2 || !g->phrases) return;
    int fixed = 0;
    for (size_t f = 0; f < sizeof(kFixes) / sizeof(kFixes[0]); f++) {
        if (kFixes[f].part != g->part_number) continue;
        for (uint32_t i = 0; i < g->phrases->count; i++) {
            PetkaPhrase *ph = &g->phrases->phrases[i];
            if (strcasecmp(ph->wav_name, kFixes[f].wav) != 0 || !same_text(ph->text, kFixes[f].was)) continue;
            char now[1024];
            utf8_to_cp1251(kFixes[f].now, now, sizeof(now));
            char *text = (char *)malloc(strlen(now) + 1);
            if (!text) return;
            strcpy(text, now);
            free(ph->text);
            ph->text = text;
            fixed++;
        }
    }
    if (g->trace || getenv("PETKA_TRACE")) fprintf(stderr, "phrasefix: %d lines of %s corrected\n", fixed, g->part);
}
